// Turns data/parts.json into db/seed.sql: plain INSERT statements for db/schema.sql.
//   node scripts/seed-sql.mjs
// Load with:  psql "$DATABASE_URL" -f db/schema.sql -f db/seed.sql
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(ROOT, 'data/parts.json'), 'utf8'));

globalThis.GENE = {};
await import(pathToFileURL(join(ROOT, 'src/js/lib/parts-meta.js')).href);
const CAT = globalThis.GENE.parts;

// SQL literal: quotes doubled, NULL for missing values
const lit = v => (v === null || v === undefined ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'");
const rows = (table, cols, list, toRow, batch = 500) => {
  const out = [];
  for (let i = 0; i < list.length; i += batch) {
    const chunk = list.slice(i, i + batch).map(item => '  (' + toRow(item).join(', ') + ')');
    out.push('insert into ' + table + ' (' + cols + ') values\n' + chunk.join(',\n') + ';');
  }
  return out.join('\n\n');
};

const types = Object.keys(CAT);
const parts = data.parts;

const sql = [
  '-- Generated by scripts/seed-sql.mjs from data/parts.json (synthetic demo data).',
  '-- ' + data.meta.count + ' parts, ' + data.contributors.length + ' contributors.',
  'begin;',
  '',
  rows('part_types', 'type, name, plural, material, planning_kg, co2_per_kg', types, t => [
    lit(t), lit(CAT[t].name), lit(CAT[t].plural), lit(CAT[t].material), CAT[t].kg, CAT[t].co2PerKg
  ]),
  '',
  rows('contributors', 'id, name, kind, zone', data.contributors, c => [lit(c.id), lit(c.name), lit(c.kind), lit(c.zone)]),
  '',
  rows('parts', 'id, type, contributor_id, zone, condition, safety, status, kg, added_on', parts, p => [
    lit(p.id), lit(p.type), lit(p.contributor), lit(p.zone), lit(p.condition), lit(p.safety), lit(p.status), p.kg, lit(p.added)
  ]),
  '',
  rows('part_dimensions', 'part_id, length_mm, width_mm, height_mm', parts, p => [lit(p.id), p.dims[0], p.dims[1], p.dims[2]]),
  '',
  rows('part_colours', 'part_id, hex, name', parts, p => [lit(p.id), lit(p.colour.hex), lit(p.colour.name)]),
  '',
  rows('part_tags', 'part_id, tag', parts.flatMap(p => p.tags.map(tag => ({ id: p.id, tag }))), r => [lit(r.id), lit(r.tag)]),
  '',
  'commit;',
  ''
].join('\n');

const out = join(ROOT, 'db/seed.sql');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, sql);
console.log('wrote db/seed.sql:', parts.length, 'parts,', data.contributors.length, 'contributors');
